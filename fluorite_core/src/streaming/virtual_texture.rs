//! Hardware-Accelerated Virtual Texturing (Sparse Physical Tile Cache).
//!
//! Maps multi-gigabyte virtual textures (e.g. 64k x 64k) to a small physical tile cache (e.g. 2k x 2k)
//! with asynchronous page streaming and GPU feedback readbacks.

use serde::{Deserialize, Serialize};
use std::collections::{HashMap, VecDeque};

pub const TILE_SIZE: u32 = 128; // 128x128 texels per tile
pub const TILE_BORDER: u32 = 4;  // 4-pixel border to eliminate filtering seams

/// 2D Virtual Tile Page coordinate at a given mipmap level.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct PageCoord {
    pub x: u32,
    pub y: u32,
    pub mip: u32,
}

/// Entry in the GPU Virtual Page Table.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, bytemuck::Pod, bytemuck::Zeroable)]
pub struct PageTableEntry {
    /// Physical tile X coordinate in tile pool (0..31 for 4096 physical width).
    pub physical_x: u16,
    /// Physical tile Y coordinate in tile pool.
    pub physical_y: u16,
    /// Mipmap level offset fallback if page is not yet resident.
    pub fallback_mip: u8,
    /// Residency flag: 1 if page is resident in VRAM, 0 if streaming.
    pub is_resident: u8,
    pub _pad: u16,
}

/// GPU Feedback Buffer entry generated by fragment shaders.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, bytemuck::Pod, bytemuck::Zeroable)]
pub struct FeedbackEntry {
    pub packed_page_and_mip: u32,
}

pub struct FeedbackBuffer {
    pub entries: Vec<FeedbackEntry>,
}

/// Virtual Texturing Manager.
pub struct VirtualTextureSystem {
    pub virtual_width: u32,
    pub virtual_height: u32,
    pub physical_pool_tiles_x: u32,
    pub physical_pool_tiles_y: u32,
    pub resident_pages: HashMap<PageCoord, (u32, u32)>, // Page -> (phys_x, phys_y)
    pub free_physical_slots: VecDeque<(u32, u32)>,
    pub pending_requests: VecDeque<PageCoord>,
}

impl VirtualTextureSystem {
    pub fn new(virtual_width: u32, virtual_height: u32, physical_pool_tiles: u32) -> Self {
        let mut free_slots = VecDeque::new();
        for y in 0..physical_pool_tiles {
            for x in 0..physical_pool_tiles {
                free_slots.push_back((x, y));
            }
        }

        Self {
            virtual_width,
            virtual_height,
            physical_pool_tiles_x: physical_pool_tiles,
            physical_pool_tiles_y: physical_pool_tiles,
            resident_pages: HashMap::new(),
            free_physical_slots: free_slots,
            pending_requests: VecDeque::new(),
        }
    }

    /// Processes GPU feedback buffer to determine missing pages requiring streaming from NVMe.
    pub fn process_feedback(&mut self, requested_pages: &[PageCoord]) {
        for &page in requested_pages {
            if !self.resident_pages.contains_key(&page) && !self.pending_requests.contains(&page) {
                self.pending_requests.push_back(page);
            }
        }
    }

    /// Commits streamed tile data into a physical VRAM slot.
    pub fn commit_tile(&mut self, page: PageCoord) -> Option<(u32, u32)> {
        if let Some((phys_x, phys_y)) = self.free_physical_slots.pop_front() {
            self.resident_pages.insert(page, (phys_x, phys_y));
            Some((phys_x, phys_y))
        } else {
            // Evict least-recently used page if pool is saturated
            if let Some((evicted_page, (evicted_x, evicted_y))) = self.resident_pages.iter().next().map(|(k, v)| (*k, *v)) {
                self.resident_pages.remove(&evicted_page);
                self.resident_pages.insert(page, (evicted_x, evicted_y));
                Some((evicted_x, evicted_y))
            } else {
                None
            }
        }
    }

    /// Total resident page count in VRAM.
    pub fn resident_page_count(&self) -> usize {
        self.resident_pages.len()
    }

    /// Pending NVMe streaming request count.
    pub fn pending_request_count(&self) -> usize {
        self.pending_requests.len()
    }
}
