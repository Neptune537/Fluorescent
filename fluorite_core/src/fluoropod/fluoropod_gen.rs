//! Fluoropod Code-Gen Toolchain & Binary Schema Generator.
//!
//! Generates type-safe Dart classes, binary serialization offsets, and FFI bindings
//! from native Rust struct definitions.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FieldSchema {
    pub name: String,
    pub rust_type: String,
    pub dart_type: String,
    pub offset_bytes: usize,
    pub size_bytes: usize,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FluoropodSchema {
    pub struct_name: String,
    pub total_size_bytes: usize,
    pub fields: Vec<FieldSchema>,
}

pub struct BinarySchemaGenerator;

impl BinarySchemaGenerator {
    /// Generates a Dart class code with zero-copy ByteData getters for a given schema.
    pub fn generate_dart_class(schema: &FluoropodSchema) -> String {
        let mut out = String::new();
        out.push_str("// Auto-generated by fluoropod_gen. DO NOT EDIT.\n");
        out.push_str("import 'dart:typed_data';\n\n");
        out.push_str(&format!("class {} {{\n", schema.struct_name));
        out.push_str("  final ByteData _data;\n");
        out.push_str("  final int offset;\n\n");
        out.push_str(&format!("  const {}(this._data, [this.offset = 0]);\n\n", schema.struct_name));

        for field in &schema.fields {
            match field.rust_type.as_str() {
                "f32" => {
                    out.push_str(&format!(
                        "  double get {} => _data.getFloat32(offset + {}, Endian.little);\n",
                        field.name, field.offset_bytes
                    ));
                }
                "u32" => {
                    out.push_str(&format!(
                        "  int get {} => _data.getUint32(offset + {}, Endian.little);\n",
                        field.name, field.offset_bytes
                    ));
                }
                "u64" => {
                    out.push_str(&format!(
                        "  int get {} => _data.getUint64(offset + {}, Endian.little);\n",
                        field.name, field.offset_bytes
                    ));
                }
                "u8" => {
                    out.push_str(&format!(
                        "  int get {} => _data.getUint8(offset + {});\n",
                        field.name, field.offset_bytes
                    ));
                }
                _ => {}
            }
        }

        out.push_str("}\n");
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_dart_generation() {
        let schema = FluoropodSchema {
            struct_name: "PlayerTelemetry".into(),
            total_size_bytes: 16,
            fields: vec![
                FieldSchema {
                    name: "health".into(),
                    rust_type: "f32".into(),
                    dart_type: "double".into(),
                    offset_bytes: 0,
                    size_bytes: 4,
                },
                FieldSchema {
                    name: "score".into(),
                    rust_type: "u32".into(),
                    dart_type: "int".into(),
                    offset_bytes: 4,
                    size_bytes: 4,
                },
            ],
        };

        let dart_code = BinarySchemaGenerator::generate_dart_class(&schema);
        assert!(dart_code.contains("class PlayerTelemetry"));
        assert!(dart_code.contains("double get health"));
        assert!(dart_code.contains("int get score"));
    }
}
